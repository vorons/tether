static void open_tether_api(lua_State *L)
{
    /* idempotent; needed before any libcurl use (TLS backend init, zlib) */
    curl_global_init(CURL_GLOBAL_DEFAULT);
    luaL_newlib(L, tether_api);
    lua_setglobal(L, "tether");
}

/* Load a Lua chunk, execute it, store its single return value in global `name`. */
static int load_module(lua_State *L, const char *src, const char *name)
{
    int lr = luaL_loadstring(L, src);
    if (lr != LUA_OK) {
        fprintf(stderr, "tether: load %s: %s\n", name, lua_tostring(L, -1));
        lua_pop(L, 1);
        return 1;
    }
    lr = lua_pcall(L, 0, 1, 0);
    if (lr != LUA_OK) {
        fprintf(stderr, "tether: run %s: %s\n", name, lua_tostring(L, -1));
        lua_pop(L, 1);
        return 1;
    }
    if (lua_isnil(L, -1)) {
        lua_pop(L, 1);
        lua_newtable(L);
    }
    lua_setglobal(L, name);
    return 0;
}

int main(int argc, char **argv)
{
    int interactive = isatty(STDIN_FILENO) == 1;

    /* Install signal handling in every mode: SIGINT/SIGTERM restore the
       terminal (no-op when raw mode was never enabled) and exit cleanly.
       SIGWINCH only matters for the TUI. */
    setup_signal_handlers();

    if (interactive) {
        if (init_termios() != 0) {
            perror("tcsetattr");
            return 1;
        }
        atexit(restore_termios);
    }

    lua_State *L = luaL_newstate();
    if (!L) {
        fprintf(stderr, "tether: cannot allocate lua state\n");
        restore_termios();
        return 1;
    }
    luaL_openlibs(L);
    open_tether_api(L);

    int rc = 0;
    struct { const char *src; const char *name; } mods[] = {
        /* provider_common first: session/agent resolve their JSON helpers to it */
        { provider_common_lua,    "provider_common"    },
        /* retry: pure policy module api/agent apply (see src/tether/retry.lua) */
        { retry_lua,   "retry"   },
        { session_lua, "session" },
        { diff_lua,   "diff"   },
        /* ask: the structured-question rules ui/agent apply (src/tether/ask.lua) */
        { ask_lua,    "ask"    },
        /* confirm_policy: pure should_confirm/approve_key policy (src/tether/confirm_policy.lua) */
        { confirm_policy_lua, "confirm_policy" },
        /* auth: OAuth/API-key store for /login /logout (src/tether/auth.lua) */
        { auth_lua, "auth" },
        /* transcript: visible conversation model; ui loads it before State */
        { transcript_lua, "transcript" },
        /* commands: session lifecycle + slash side effects (src/tether/commands.lua) */
        { commands_lua, "commands" },
        /* turn: control facade over agent; abort seam + busy reset (src/tether/turn.lua) */
        { turn_lua, "turn" },
        { ui_lua,     "ui"     },
        { config_lua, "config" },
        { tools_lua,  "tools"  },
        { provider_openai_lua,    "provider_openai"    },
        { provider_anthropic_lua, "provider_anthropic" },
        { provider_gemini_lua,    "provider_gemini"    },
        { api_lua,    "api"    },
        { context_lua, "context" },
        { agent_lua,  "agent"  },
        { app_lua,    "app"    },
    };
    for (size_t i = 0; i < sizeof(mods)/sizeof(mods[0]); i++) {
        if (load_module(L, mods[i].src, mods[i].name) != 0) { rc = 1; break; }
    }
    if (rc == 0) {
        /* Push argv to Lua 'arg' global for CLI parsing */
        lua_newtable(L);
        for (int i = 1; i < argc; i++) {
            lua_pushstring(L, argv[i]);
            lua_rawseti(L, -2, i);
        }
        lua_setglobal(L, "arg");
        lua_getglobal(L, "app");
        lua_getfield(L, -1, "run");
        int rc2 = lua_pcall(L, 0, 0, 0);
        if (rc2 != LUA_OK) {
            fprintf(stderr, "tether: app.run: %s\n", lua_tostring(L, -1));
            lua_pop(L, 1);
            rc = 1;
        }
        lua_pop(L, 1);
    }

    lua_close(L);
    restore_termios();
    return rc == 0 ? 0 : 1;
}
